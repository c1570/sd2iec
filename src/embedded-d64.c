#ifdef CONFIG_EMBEDDED_D64

/* generated by scripts/bindata.pl during the build */
#include "embedded-d64-data.h"

#define EMBEDDED_D64_NAME "1541_test_demo.d64"

uint8_t embedded_d64_active;

static uint32_t embedded_d64_pos;

uint8_t embedded_d64_read(uint32_t offset, void *buffer, uint16_t bytes) {
  uint16_t wanted = bytes;

  if (offset == (uint32_t)-1)
    offset = embedded_d64_pos;

  if (offset >= embedded_d64_data_len)
    return 1;

  if (bytes > embedded_d64_data_len - offset)
    bytes = embedded_d64_data_len - offset;

  memcpy(buffer, embedded_d64_data + offset, bytes);
  embedded_d64_pos = offset + bytes;

  return (bytes == wanted) ? 0 : 1;
}

void embedded_d64_mount(uint8_t preserve_path) {
  path_t path;
  uint8_t part = 0;

  partition[part].fop = &d64ops;

  /* A zeroed FIL is enough: the D64 code only uses fsize and flag, */
  /* image_read/image_write are redirected to the built-in array.    */
  memset(&partition[part].imagehandle, 0, sizeof(partition[part].imagehandle));
  partition[part].imagehandle.fsize = embedded_d64_data_len;

  memset(&path, 0, sizeof(path));
  path.part = part;
  embedded_d64_pos = 0;

  /* Drop BAM buffers from a previous mount before allocating new ones */
  embedded_d64_active = 0;
  d64_invalidate();

  if (d64_mount(&path, (uint8_t *)EMBEDDED_D64_NAME)) {
    max_part = 0;
    return;
  }

  /* Start in the root directory of the image */
  partition[part].current_dir = path.dir;

  embedded_d64_active = 1;
  max_part = 1;
  disk_state = DISK_OK;

  if (!preserve_path) {
    current_part = 0;
    display_current_part(0);
    set_changelist(NULL, NULLSTRING);
    previous_file_dirent.name[0] = 0;
  }

  p00cache_invalidate();
}

#endif
